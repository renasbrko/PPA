// ===== Language Manager =====
const LangManager = {
  current: localStorage.getItem('PPAland_lang') || 'ar',

  get(key) {
    return translations[this.current][key] || translations['ar'][key] || key;
  },

  set(lang) {
    this.current = lang;
    localStorage.setItem('PPAland_lang', lang);
    this.apply();
  },

  apply() {
    const t = translations[this.current];
    document.documentElement.lang = t.lang;
    document.documentElement.dir = t.dir;
    document.body.style.fontFamily = t.fontFamily;

    // Update all elements with data-lang attribute
    document.querySelectorAll('[data-lang]').forEach(el => {
      const key = el.getAttribute('data-lang');
      const val = this.get(key);
      if (val) el.textContent = val;
    });

    // Update placeholders
    document.querySelectorAll('[data-lang-placeholder]').forEach(el => {
      const key = el.getAttribute('data-lang-placeholder');
      el.placeholder = this.get(key);
    });

    // Update lang switcher buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.remove('active');
      if (btn.dataset.lang === this.current) btn.classList.add('active');
    });
  },

  init() {
    this.apply();
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', () => this.set(btn.dataset.lang));
    });
  }
};
